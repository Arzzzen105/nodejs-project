import { describe, beforeEach, afterEach, test, expect } from 'vitest';
import fs from 'node:fs/promises';
import path from 'node:path';
import { v7 as uuidv7 } from 'uuid';
import {
    FileDatabase,
    DatabaseError,
} from '../../src/storage/file-database.js';
import {
    TEST_COLLECTION,
    createTestConfig,
    createTempDir,
    removeDir,
    writeCollectionConfig,
    fileExists,
} from '../helpers/temp-db.js';

describe('CRUD through FileDatabase', () => {
    let root;
    let directory;
    let db;

    function recordPath(id) {
        return path.join(directory, `${id}.json`);
    }

    beforeEach(async () => {
        root = await createTempDir();
        directory = await writeCollectionConfig(
            root,
            TEST_COLLECTION,
            createTestConfig()
        );
        db = await new FileDatabase(root).init();
    });

    afterEach(async () => {
        await removeDir(root);
    });

    describe('create', () => {
        test('creating a record with valid data should succeed', async () => {
            // ARRANGE
            const recordData = {
                title: 'Test Record',
                description: 'This is a test record.',
                number: 42,
            };

            // ACT
            const createdRecord = await db.create(TEST_COLLECTION, recordData);

            // ASSERT
            expect(createdRecord).toHaveProperty('id');
            expect(createdRecord.title).toBe(recordData.title);
            expect(createdRecord.description).toBe(recordData.description);
            expect(createdRecord.number).toBe(recordData.number);
            expect(await fileExists(recordPath(createdRecord.id))).toBe(true);
        });

        test('creating a record with invalid data should throw an error', async () => {
            // ARRANGE
            const invalidRecordData = {
                description: 'This is a test record.',
                number: 50,
            };

            // ACT & ASSERT
            await expect(
                db.create(TEST_COLLECTION, invalidRecordData)
            ).rejects.toThrow('"title" is required.');
        });

        test('creating a record with an "id" field should throw an error', async () => {
            // ARRANGE
            const recordDataWithId = {
                id: uuidv7(),
                title: 'Test Record with ID',
            };

            // ACT & ASSERT
            await expect(
                db.create(TEST_COLLECTION, recordDataWithId)
            ).rejects.toThrow('The "id" field is generated by the server.');
        });

        test('creating a record from a non-object body should throw an error', async () => {
            // ACT & ASSERT
            await expect(
                db.create(TEST_COLLECTION, ['title'])
            ).rejects.toMatchObject({
                code: 'INVALID_BODY',
                status: 400,
            });
        });

        test('writes the record to disk as JSON', async () => {
            // ACT
            const createdRecord = await db.create(TEST_COLLECTION, {
                title: 'On disk',
            });

            // ASSERT
            const onDisk = JSON.parse(
                await fs.readFile(recordPath(createdRecord.id), 'utf8')
            );
            expect(onDisk).toEqual(createdRecord);
        });

        test('atomic write does not leave leftover .tmp files', async () => {
            // ARRANGE & ACT
            await db.create(TEST_COLLECTION, { title: 'Atomic Test' });

            // ASSERT
            const dirFiles = await fs.readdir(directory);
            const tmpFiles = dirFiles.filter((file) => file.endsWith('.tmp'));
            expect(tmpFiles.length).toBe(0);
        });

        test('returned record is a copy', async () => {
            // ARRANGE
            const createdRecord = await db.create(TEST_COLLECTION, {
                title: 'Original',
            });

            // ACT
            createdRecord.title = 'Mutated';

            // ASSERT
            const fetched = await db.get(TEST_COLLECTION, createdRecord.id);
            expect(fetched.title).toBe('Original');
        });
    });

    describe('update', () => {
        test('fully updating a record with valid data should succeed', async () => {
            // ARRANGE
            const createdRecord = await db.create(TEST_COLLECTION, {
                title: 'Test Record',
                description: 'This is a test record.',
                number: 42,
            });
            const updatedData = {
                title: 'Updated Test Record',
                description: 'This is an updated test record.',
                number: 50,
            };

            // ACT
            const updatedRecord = await db.update(
                TEST_COLLECTION,
                createdRecord.id,
                updatedData,
                { replace: true }
            );

            // ASSERT
            expect(updatedRecord).toEqual({ ...createdRecord, ...updatedData });
        });

        test('fully updating drops fields missing from the new document', async () => {
            // ARRANGE
            const createdRecord = await db.create(TEST_COLLECTION, {
                title: 'Test Record',
                description: 'Will be removed',
            });

            // ACT
            const updatedRecord = await db.update(
                TEST_COLLECTION,
                createdRecord.id,
                { title: 'Replaced' },
                { replace: true }
            );

            // ASSERT
            expect(updatedRecord).toEqual({
                id: createdRecord.id,
                title: 'Replaced',
            });
        });

        test('fully updating a record with invalid data should throw an error', async () => {
            // ARRANGE
            const createdRecord = await db.create(TEST_COLLECTION, {
                title: 'Test Record',
                number: 42,
            });
            const invalidUpdatedData = {
                description: 'This is an updated test record without a title.',
                number: 50,
            };

            // ACT & ASSERT
            await expect(
                db.update(
                    TEST_COLLECTION,
                    createdRecord.id,
                    invalidUpdatedData,
                    {
                        replace: true,
                    }
                )
            ).rejects.toThrow('"title" is required.');
        });

        test('fully updating a record with an "id" field should throw an error', async () => {
            // ARRANGE
            const createdRecord = await db.create(TEST_COLLECTION, {
                title: 'Test',
            });

            // ACT & ASSERT
            await expect(
                db.update(
                    TEST_COLLECTION,
                    createdRecord.id,
                    { id: uuidv7(), title: 'Updated Test Record' },
                    { replace: true }
                )
            ).rejects.toThrow('The "id" field cannot be changed.');
        });

        test('fully updating a non-existent record should throw an error', async () => {
            // ACT & ASSERT
            await expect(
                db.update(
                    TEST_COLLECTION,
                    uuidv7(),
                    { title: 'Updated Test Record' },
                    { replace: true }
                )
            ).rejects.toThrow('Record not found.');
        });

        test('patching a record with valid data should succeed', async () => {
            // ARRANGE
            const createdRecord = await db.create(TEST_COLLECTION, {
                title: 'Test Record',
                description: 'This is a test record.',
                number: 42,
            });
            const patchData = { description: 'This is a patched test record.' };

            // ACT
            const patchedRecord = await db.update(
                TEST_COLLECTION,
                createdRecord.id,
                patchData
            );

            // ASSERT
            expect(patchedRecord).toEqual({ ...createdRecord, ...patchData });
            await expect(
                db.get(TEST_COLLECTION, createdRecord.id)
            ).resolves.toEqual(patchedRecord);
        });

        test('patching a record with invalid data should throw an error', async () => {
            // ARRANGE
            const createdRecord = await db.create(TEST_COLLECTION, {
                title: 'Test Record',
                number: 42,
            });

            // ACT & ASSERT
            await expect(
                db.update(TEST_COLLECTION, createdRecord.id, {
                    number: 'not-a-number',
                })
            ).rejects.toThrow('"number" must be integer.');
        });

        test('failed update leaves the record unchanged', async () => {
            // ARRANGE
            const createdRecord = await db.create(TEST_COLLECTION, {
                title: 'Stable',
                number: 1,
            });

            // ACT
            await db
                .update(TEST_COLLECTION, createdRecord.id, { number: 1000 })
                .catch(() => {});

            // ASSERT
            await expect(
                db.get(TEST_COLLECTION, createdRecord.id)
            ).resolves.toEqual(createdRecord);
        });

        test('patching a record with an "id" field should throw an error', async () => {
            // ARRANGE
            const createdRecord = await db.create(TEST_COLLECTION, {
                title: 'Test',
            });

            // ACT & ASSERT
            await expect(
                db.update(TEST_COLLECTION, createdRecord.id, {
                    id: uuidv7(),
                    description: 'This is a patched test record.',
                })
            ).rejects.toThrow('The "id" field cannot be changed.');
        });

        test('updating with a non-object body should throw an error', async () => {
            // ARRANGE
            const createdRecord = await db.create(TEST_COLLECTION, {
                title: 'Test',
            });

            // ACT & ASSERT
            await expect(
                db.update(TEST_COLLECTION, createdRecord.id, null)
            ).rejects.toMatchObject({ code: 'INVALID_BODY' });
        });

        test('updating indexed field updates in-memory index correctly', async () => {
            // ARRANGE
            const record = await db.create(TEST_COLLECTION, {
                title: 'Old Title',
            });

            // ACT & ASSERT
            const found = await db.list(TEST_COLLECTION, {
                where: { title: 'Old Title' },
            });
            expect(found.total).toBe(1);

            await db.update(TEST_COLLECTION, record.id, { title: 'New Title' });

            const oldQuery = await db.list(TEST_COLLECTION, {
                where: { title: 'Old Title' },
            });
            expect(oldQuery.total).toBe(0);

            const newQuery = await db.list(TEST_COLLECTION, {
                where: { title: 'New Title' },
            });
            expect(newQuery.total).toBe(1);
            expect(newQuery.items[0].id).toBe(record.id);
        });

        test(
            'concurrent updates on the same record execute sequentially via lock',
            { repeats: 3 },
            async () => {
                // ARRANGE
                const record = await db.create(TEST_COLLECTION, {
                    title: 'Initial',
                    number: 0,
                });
                const updatesCount = 10;

                // ACT
                const updates = Array.from({ length: updatesCount }, (_, i) =>
                    db.update(TEST_COLLECTION, record.id, { number: i + 1 })
                );

                // ASSERT
                await expect(Promise.all(updates)).resolves.not.toThrow();
                const finalRecord = await db.get(TEST_COLLECTION, record.id);
                expect(finalRecord.number).toEqual(updatesCount);
            }
        );
    });

    describe('delete', () => {
        test('deleting an existing record should succeed', async () => {
            // ARRANGE
            const createdRecord = await db.create(TEST_COLLECTION, {
                title: 'Test',
            });

            // ACT
            await db.delete(TEST_COLLECTION, createdRecord.id);

            // ASSERT
            await expect(
                db.get(TEST_COLLECTION, createdRecord.id)
            ).rejects.toThrow('Record not found.');
            expect(await fileExists(recordPath(createdRecord.id))).toBe(false);
        });

        test('deleting a non-existent record should throw an error', async () => {
            // ACT & ASSERT
            await expect(db.delete(TEST_COLLECTION, uuidv7())).rejects.toThrow(
                'Record not found.'
            );
        });

        test('deleting with an invalid id should throw an error', async () => {
            // ACT & ASSERT
            await expect(
                db.delete(TEST_COLLECTION, 'nope')
            ).rejects.toBeInstanceOf(DatabaseError);
        });

        test('deleting record removes it from index', async () => {
            // ARRANGE
            const record = await db.create(TEST_COLLECTION, {
                title: 'To Be Deleted',
            });

            // ACT
            await db.delete(TEST_COLLECTION, record.id);

            // ASSERT
            const result = await db.list(TEST_COLLECTION, {
                where: { title: 'To Be Deleted' },
            });
            expect(result.total).toBe(0);
            expect(result.items).toHaveLength(0);
        });

        test('concurrent deletes of the same record succeed only once', async () => {
            // ARRANGE
            const record = await db.create(TEST_COLLECTION, { title: 'Once' });

            // ACT
            const results = await Promise.allSettled([
                db.delete(TEST_COLLECTION, record.id),
                db.delete(TEST_COLLECTION, record.id),
            ]);

            // ASSERT
            expect(results.map((r) => r.status).sort()).toEqual([
                'fulfilled',
                'rejected',
            ]);
        });
    });
});
