import { describe, beforeEach, afterEach, test, expect } from 'vitest';
import fs from 'node:fs/promises';
import path from 'node:path';
import { v7 as uuidv7 } from 'uuid';
import {
    FileDatabase,
    eq,
    gt,
    gte,
    lt,
    lte,
    and,
    or,
    custom,
    inList,
} from '../../src/storage/file-database.js';

describe('Filebase Engine', () => {
    const testDbPath = path.resolve(process.cwd(), 'tests', 'tmp-engine-db');
    let db;

    beforeEach(async () => {
        await fs.mkdir(testDbPath, { recursive: true });

        const mockSchemaPath = path.join(testDbPath, 'test-collection');
        await fs.mkdir(mockSchemaPath, { recursive: true });
        await fs.writeFile(
            path.join(mockSchemaPath, 'config.json'),
            JSON.stringify({
                table: 'test-collection',
                primaryKey: 'id',
                columns: {
                    title: { type: 'string', required: true },
                    description: { type: 'string', required: false },
                    number: {
                        type: 'integer',
                        required: false,
                        min: 0,
                        max: 100,
                    },
                },
                indexes: ['title'],
            })
        );
        db = new FileDatabase(testDbPath);
        await db.init();
    });

    afterEach(async () => {
        await fs.rm(testDbPath, { recursive: true, force: true });
    });

    test('after initialization engine has valid collection and its schema', async () => {
        expect(db.collections().includes('test-collection')).toBe(true);
    });

    function entityPersisted(id) {
        const recordPath = path.join(
            testDbPath,
            'test-collection',
            `${id}.json`
        );
        return fs
            .access(recordPath)
            .then(() => true)
            .catch(() => false);
    }

    test('creating a record with valid data should succeed', async () => {
        // ARRANGE

        const recordData = {
            title: 'Test Record',
            description: 'This is a test record.',
            number: 42,
        };

        // ACT

        const createdRecord = await db.create('test-collection', recordData);

        // ASSERT

        expect(createdRecord).toHaveProperty('id');
        expect(createdRecord.title).toBe(recordData.title);
        expect(createdRecord.description).toBe(recordData.description);
        expect(createdRecord.number).toBe(recordData.number);
        expect(await entityPersisted(createdRecord.id)).toBe(true);
    });

    test('creating a record with invalid data should throw an error', async () => {
        // ARRANGE

        const invalidRecordData = {
            description: 'This is a test record.',
            number: 50,
        };

        // ACT & ASSERT

        await expect(
            db.create('test-collection', invalidRecordData)
        ).rejects.toThrow('"title" is required.');
    });

    test('creating a record with an "id" field should throw an error', async () => {
        // ARRANGE

        const recordDataWithId = {
            id: uuidv7(),
            title: 'Test Record with ID',
            description: 'This is a test record with an ID.',
            number: 42,
        };

        // ACT & ASSERT

        await expect(
            db.create('test-collection', recordDataWithId)
        ).rejects.toThrow('The "id" field is generated by the server.');
    });

    test('getting a record by ID should return the correct record', async () => {
        // ARRANGE

        const recordData = {
            title: 'Test Record',
            description: 'This is a test record.',
            number: 42,
        };
        const createdRecord = await db.create('test-collection', recordData);

        // ACT

        const fetchedRecord = await db.get('test-collection', createdRecord.id);

        // ASSERT

        expect(fetchedRecord).toEqual(createdRecord);
    });

    test('getting a record with an invalid ID should throw an error', async () => {
        // ARRANGE

        const invalidId = 'invalid-id';

        // ACT & ASSERT

        await expect(db.get('test-collection', invalidId)).rejects.toThrow(
            '"id" must be a UUID.'
        );
    });

    test('getting a record with a non-v7 UUID should throw an invalid id error', async () => {
        // ARRANGE

        const nonV7Id = '123e4567-e89b-12d3-a456-426614174000';

        // ACT & ASSERT

        await expect(db.get('test-collection', nonV7Id)).rejects.toThrow(
            '"id" must be a UUID.'
        );
    });

    test('getting a non-existent record should throw an error', async () => {
        // ARRANGE

        const nonExistentId = uuidv7();

        // ACT & ASSERT

        await expect(db.get('test-collection', nonExistentId)).rejects.toThrow(
            'Record not found.'
        );
    });

    test('fetching all records should return an array of records', async () => {
        // ARRANGE

        const recordData1 = {
            title: 'Test Record 1',
            description: 'This is the first test record.',
            number: 10,
        };
        const recordData2 = {
            title: 'Test Record 2',
            description: 'This is the second test record.',
            number: 20,
        };
        const createdRecord1 = await db.create('test-collection', recordData1);
        const createdRecord2 = await db.create('test-collection', recordData2);

        // ACT

        const allRecords = await db.list('test-collection');

        // ASSERT

        expect(allRecords.total).toEqual(2);
        expect(allRecords.items).toEqual(
            expect.arrayContaining([createdRecord1, createdRecord2])
        );
    });

    test('fetching records with filter sould return only matching records', async () => {
        // ARRANGE

        const recordData1 = {
            title: 'Test Record 1',
            description: 'This is the first test record.',
            number: 10,
        };
        const recordData2 = {
            title: 'Test Record 2',
            description: 'This is the second test record.',
            number: 20,
        };
        const createdRecord1 = await db.create('test-collection', recordData1);
        await db.create('test-collection', recordData2);

        // ACT

        const filteredRecords = await db.list('test-collection', {
            where: { number: 10 },
        });

        // ASSERT

        expect(filteredRecords.total).toEqual(1);
        expect(filteredRecords.items).toEqual(
            expect.arrayContaining([createdRecord1])
        );
    });

    test('fetching records with pagination should return correct subset of records', async () => {
        // ARRANGE

        const recordData1 = {
            title: 'Test Record 1',
            description: 'This is the first test record.',
            number: 10,
        };
        const recordData2 = {
            title: 'Test Record 2',
            description: 'This is the second test record.',
            number: 20,
        };
        await db.create('test-collection', recordData1);
        const createdRecord2 = await db.create('test-collection', recordData2);

        // ACT

        const paginatedRecords = await db.list('test-collection', {
            limit: 1,
            offset: 1,
        });

        // ASSERT

        expect(paginatedRecords.total).toEqual(2);
        expect(paginatedRecords.items.length).toEqual(1);
        expect(paginatedRecords.items[0]).toEqual(createdRecord2);
    });

    test('fetching records with multiple filter parameters should return only matching records', async () => {
        // ARRANGE

        const recordData1 = {
            title: 'Test Record 1',
            description: 'This is the first test record.',
            number: 10,
        };
        const recordData2 = {
            title: 'Test Record 2',
            description: 'This is the second test record.',
            number: 20,
        };
        const createdRecord1 = await db.create('test-collection', recordData1);
        await db.create('test-collection', recordData2);

        // ACT

        const filteredRecords = await db.list('test-collection', {
            where: { number: 10, title: 'Test Record 1' },
        });

        // ASSERT

        expect(filteredRecords.total).toEqual(1);
        expect(filteredRecords.items).toEqual(
            expect.arrayContaining([createdRecord1])
        );
    });

    test('fetching records with invalid pagination parameters should throw an error', async () => {
        // ACT & ASSERT

        await expect(
            db.list('test-collection', { limit: 10000, offset: 0 })
        ).rejects.toThrow(
            '"limit" must be 1–500 and "offset" must be zero or greater.'
        );
        await expect(
            db.list('test-collection', { limit: 1, offset: -1 })
        ).rejects.toThrow(
            '"limit" must be 1–500 and "offset" must be zero or greater.'
        );
    });

    test('fetching records with invalid filter parameters should throw an error', async () => {
        // ACT & ASSERT

        await expect(
            db.list('test-collection', { where: { number: 'not-a-number' } })
        ).rejects.toThrow('"number" must be integer.');
    });

    test('fetching records with invalid filter fields should throw an error', async () => {
        // ACT & ASSERT

        await expect(
            db.list('test-collection', {
                where: { nonExistentField: 'some-value' },
            })
        ).rejects.toThrow('Unknown filter field "nonExistentField".');
    });

    test('fully updating a record with valid data should succeed', async () => {
        // ARRANGE

        const recordData = {
            title: 'Test Record',
            description: 'This is a test record.',
            number: 42,
        };
        const createdRecord = await db.create('test-collection', recordData);
        const updatedData = {
            title: 'Updated Test Record',
            description: 'This is an updated test record.',
            number: 50,
        };
        // ACT
        const updatedRecord = await db.update(
            'test-collection',
            createdRecord.id,
            updatedData,
            { replace: true }
        );

        // ASSERT
        expect(updatedRecord).toEqual({
            ...createdRecord,
            ...updatedData,
        });
    });

    test('fully updating a record with invalid data should throw an error', async () => {
        // ARRANGE

        const recordData = {
            title: 'Test Record',
            description: 'This is a test record.',
            number: 42,
        };
        const createdRecord = await db.create('test-collection', recordData);
        const invalidUpdatedData = {
            description: 'This is an updated test record without a title.',
            number: 50,
        };
        // ACT & ASSERT
        await expect(
            db.update('test-collection', createdRecord.id, invalidUpdatedData, {
                replace: true,
            })
        ).rejects.toThrow('"title" is required.');
    });

    test('fully updating a record with an "id" field should throw an error', async () => {
        // ARRANGE

        const recordData = {
            title: 'Test Record',
            description: 'This is a test record.',
            number: 42,
        };
        const createdRecord = await db.create('test-collection', recordData);
        const updatedDataWithId = {
            id: uuidv7(),
            title: 'Updated Test Record',
            description: 'This is an updated test record.',
            number: 50,
        };

        // ACT & ASSERT
        await expect(
            db.update('test-collection', createdRecord.id, updatedDataWithId, {
                replace: true,
            })
        ).rejects.toThrow('The "id" field cannot be changed.');
    });

    test('fully updating a non-existent record should throw an error', async () => {
        // ARRANGE

        const nonExistentId = uuidv7();
        const updatedData = {
            title: 'Updated Test Record',
            description: 'This is an updated test record.',
            number: 50,
        };

        // ACT & ASSERT
        await expect(
            db.update('test-collection', nonExistentId, updatedData, {
                replace: true,
            })
        ).rejects.toThrow('Record not found.');
    });

    test('patching a record with valid data should succeed', async () => {
        // ARRANGE

        const recordData = {
            title: 'Test Record',
            description: 'This is a test record.',
            number: 42,
        };
        const createdRecord = await db.create('test-collection', recordData);
        const patchData = {
            description: 'This is a patched test record.',
        };

        // ACT
        const patchedRecord = await db.update(
            'test-collection',
            createdRecord.id,
            patchData
        );

        // ASSERT
        expect(patchedRecord).toEqual({
            ...createdRecord,
            ...patchData,
        });
    });

    test('patching a record with invalid data should throw an error', async () => {
        // ARRANGE

        const recordData = {
            title: 'Test Record',
            description: 'This is a test record.',
            number: 42,
        };
        const createdRecord = await db.create('test-collection', recordData);
        const invalidPatchData = {
            number: 'not-a-number',
        };

        // ACT & ASSERT
        await expect(
            db.update('test-collection', createdRecord.id, invalidPatchData)
        ).rejects.toThrow('"number" must be integer.');
    });

    test('patching a record with an "id" field should throw an error', async () => {
        // ARRANGE

        const recordData = {
            title: 'Test Record',
            description: 'This is a test record.',
            number: 42,
        };
        const createdRecord = await db.create('test-collection', recordData);
        const patchDataWithId = {
            id: uuidv7(),
            description: 'This is a patched test record.',
        };

        // ACT & ASSERT
        await expect(
            db.update('test-collection', createdRecord.id, patchDataWithId)
        ).rejects.toThrow('The "id" field cannot be changed.');
    });

    test('deleting an existing record should succeed', async () => {
        // ARRANGE

        const recordData = {
            title: 'Test Record',
            description: 'This is a test record.',
            number: 42,
        };
        const createdRecord = await db.create('test-collection', recordData);

        // ACT
        await db.delete('test-collection', createdRecord.id);

        // ASSERT
        await expect(
            db.get('test-collection', createdRecord.id)
        ).rejects.toThrow('Record not found.');
        await expect(entityPersisted(createdRecord.id)).resolves.toBe(false);
    });

    test('deleting a non-existent record should throw an error', async () => {
        // ARRANGE

        const nonExistentId = uuidv7();

        // ACT & ASSERT
        await expect(
            db.delete('test-collection', nonExistentId)
        ).rejects.toThrow('Record not found.');
    });

    test(
        'concurrent updates on the same record execute sequentially via lock',
        { repeats: 3 },
        async () => {
            // ARRANGE
            const record = await db.create('test-collection', {
                title: 'Initial',
                number: 0,
            });
            const updatesCount = 10;

            // ACT
            const updates = Array.from({ length: updatesCount }, (_, i) =>
                db.update('test-collection', record.id, { number: i + 1 })
            );

            // ASSERT
            await expect(Promise.all(updates)).resolves.not.toThrow();
            const finalRecord = await db.get('test-collection', record.id);
            expect(finalRecord.number).toEqual(updatesCount);
        }
    );

    test('atomic write does not leave leftover .tmp files', async () => {
        // ARRANGE & ACT
        await db.create('test-collection', { title: 'Atomic Test' });

        // ASSERT

        const dirFiles = await fs.readdir(
            path.join(testDbPath, 'test-collection')
        );
        const tmpFiles = dirFiles.filter((file) => file.endsWith('.tmp'));

        expect(tmpFiles.length).toBe(0);
    });

    test('updating indexed field updates in-memory index correctly', async () => {
        // ARRANGE

        const record = await db.create('test-collection', {
            title: 'Old Title',
        });

        // ACT & ASSERT

        let found = await db.list('test-collection', {
            where: { title: 'Old Title' },
        });
        expect(found.total).toBe(1);

        await db.update('test-collection', record.id, { title: 'New Title' });

        const oldQuery = await db.list('test-collection', {
            where: { title: 'Old Title' },
        });
        expect(oldQuery.total).toBe(0);

        const newQuery = await db.list('test-collection', {
            where: { title: 'New Title' },
        });
        expect(newQuery.total).toBe(1);
        expect(newQuery.items[0].id).toBe(record.id);
    });

    test('deleting record removes it from index', async () => {
        const record = await db.create('test-collection', {
            title: 'To Be Deleted',
        });

        await db.delete('test-collection', record.id);

        const result = await db.list('test-collection', {
            where: { title: 'To Be Deleted' },
        });
        expect(result.total).toBe(0);
        expect(result.items).toHaveLength(0);
    });

    test('filtering by id in where object returns the matching record', async () => {
        const r1 = await db.create('test-collection', {
            title: 'Record 1',
            number: 10,
        });
        await db.create('test-collection', {
            title: 'Record 2',
            number: 20,
        });

        const result = await db.list('test-collection', {
            where: { id: r1.id },
        });

        expect(result.total).toBe(1);
        expect(result.items).toHaveLength(1);
        expect(result.items[0].id).toBe(r1.id);
    });

    test('filtering by invalid id in where object throws an error', async () => {
        await expect(
            db.list('test-collection', {
                where: { id: 'invalid-uuid' },
            })
        ).rejects.toThrow('"id" must be a UUID.');
    });

    test('filtering by range operators in where object works as expected', async () => {
        await db.create('test-collection', { title: 'A', number: 10 });
        const r2 = await db.create('test-collection', {
            title: 'B',
            number: 20,
        });
        const r3 = await db.create('test-collection', {
            title: 'C',
            number: 30,
        });
        await db.create('test-collection', { title: 'D', number: 40 });

        const result = await db.list('test-collection', {
            where: { number: { gt: 15, lte: 30 } },
        });

        expect(result.total).toBe(2);
        expect(result.items.map((i) => i.id)).toEqual(
            expect.arrayContaining([r2.id, r3.id])
        );
    });

    test('range bounds outside column min/max are accepted', async () => {
        const r1 = await db.create('test-collection', {
            title: 'Low',
            number: 0,
        });
        const r2 = await db.create('test-collection', {
            title: 'High',
            number: 100,
        });

        const result = await db.list('test-collection', {
            where: { number: { gt: -1, lt: 101 } },
        });

        expect(result.total).toBe(2);
        expect(result.items.map((i) => i.id)).toEqual(
            expect.arrayContaining([r1.id, r2.id])
        );
    });

    test('filtering by IN operator in where object works as expected', async () => {
        const r1 = await db.create('test-collection', {
            title: 'Alpha',
            number: 1,
        });
        const r2 = await db.create('test-collection', {
            title: 'Beta',
            number: 2,
        });
        await db.create('test-collection', { title: 'Gamma', number: 3 });

        const result = await db.list('test-collection', {
            where: { title: { in: ['Alpha', 'Beta', 'Omega'] } },
        });

        expect(result.total).toBe(2);
        expect(result.items.map((i) => i.id)).toEqual(
            expect.arrayContaining([r1.id, r2.id])
        );
    });

    test('querying with structured predicates directly', async () => {
        const r1 = await db.create('test-collection', {
            title: 'Item 1',
            number: 5,
        });
        const r2 = await db.create('test-collection', {
            title: 'Item 2',
            number: 15,
        });
        const r3 = await db.create('test-collection', {
            title: 'Item 3',
            number: 25,
        });

        // Test and(eq, gte)
        const resultAnd = await db.list('test-collection', {
            predicate: and(gte('number', 10), lt('number', 20)),
        });
        expect(resultAnd.total).toBe(1);
        expect(resultAnd.items[0].id).toBe(r2.id);

        // Test inList
        const resultIn = await db.list('test-collection', {
            predicate: inList('title', ['Item 1', 'Item 3']),
        });
        expect(resultIn.total).toBe(2);
        expect(resultIn.items.map((i) => i.id)).toEqual(
            expect.arrayContaining([r1.id, r3.id])
        );

        // Test gt and lte
        const resultRange = await db.list('test-collection', {
            predicate: and(gt('number', 5), lte('number', 25)),
        });
        expect(resultRange.total).toBe(2);
        expect(resultRange.items.map((i) => i.id)).toEqual(
            expect.arrayContaining([r2.id, r3.id])
        );

        // Test or(eq, eq)
        const resultOr = await db.list('test-collection', {
            predicate: or(eq('title', 'Item 1'), eq('title', 'Item 2')),
        });
        expect(resultOr.total).toBe(2);
        expect(resultOr.items.map((i) => i.id)).toEqual(
            expect.arrayContaining([r1.id, r2.id])
        );
    });

    test('querying with custom predicate function', async () => {
        await db.create('test-collection', { title: 'Odd', number: 11 });
        const rEven = await db.create('test-collection', {
            title: 'Even',
            number: 22,
        });

        const result = await db.list('test-collection', {
            predicate: custom((record) => record.number % 2 === 0),
        });

        expect(result.total).toBe(1);
        expect(result.items[0].id).toBe(rEven.id);
    });
});
